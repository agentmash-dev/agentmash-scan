"""Static TTF instances of the agentmash.dev fonts for the share card.

resvg reads TTF/OTF only and picks a face by family + weight, so each weight is its own file.
Sources: the woff2 variable fonts agentmash.dev serves (Manrope, JetBrains Mono; both SIL OFL 1.1).

usage: python3 scripts/build-fonts.py <dir with manrope-latin.woff2 and jetbrains-mono.woff2> fonts/
needs: pip install fonttools brotli
"""

import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

# Latin, Latin-1, dashes, quotes, ellipsis: everything the card prints
UNICODES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026]

INSTANCES = [
    ("manrope-latin.woff2", "Manrope", 800, "ExtraBold", "manrope-800.ttf"),
    ("manrope-latin.woff2", "Manrope", 500, "Medium", "manrope-500.ttf"),
    ("jetbrains-mono.woff2", "JetBrains Mono", 400, "Regular", "jetbrains-mono-400.ttf"),
]


def build(src_dir: Path, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for src, family, weight, style, out in INSTANCES:
        font = TTFont(src_dir / src)
        font = instantiateVariableFont(font, {"wght": weight})
        font.flavor = None
        names = font["name"]
        for rec in list(names.names):
            if rec.nameID in (1, 2, 4, 6, 16, 17):
                names.removeNames(nameID=rec.nameID)
        full = f"{family} {style}"
        names.setName(family, 1, 3, 1, 0x409)
        names.setName("Regular", 2, 3, 1, 0x409)
        names.setName(full, 4, 3, 1, 0x409)
        names.setName(full.replace(" ", ""), 6, 3, 1, 0x409)
        names.setName(family, 16, 3, 1, 0x409)
        names.setName(style, 17, 3, 1, 0x409)
        font["OS/2"].usWeightClass = weight
        options = subset.Options()
        options.layout_features = ["kern", "liga", "tnum", "lnum"]
        options.name_IDs = ["*"]
        options.notdef_outline = True
        sub = subset.Subsetter(options)
        sub.populate(unicodes=UNICODES)
        sub.subset(font)
        path = out_dir / out
        font.save(path)
        print(f"{path} {path.stat().st_size} bytes")


def advances(path: Path) -> list:
    """advance width in em for each printable ASCII character, so the card can measure text"""
    font = TTFont(path)
    cmap = font.getBestCmap()
    upem = font["head"].unitsPerEm
    hmtx = font["hmtx"]
    return [round(hmtx[cmap[c]][0] / upem, 4) if c in cmap else 0.6 for c in range(0x20, 0x7F)]


def write_metrics(fonts_dir: Path, out: Path) -> None:
    rows = {
        "manrope800": advances(fonts_dir / "manrope-800.ttf"),
        "manrope500": advances(fonts_dir / "manrope-500.ttf"),
        "mono400": advances(fonts_dir / "jetbrains-mono-400.ttf"),
    }
    body = "\n".join(f"  {k}: [{', '.join(str(x) for x in v)}]," for k, v in rows.items())
    out.write_text(
        "// generated by scripts/build-fonts.py: advance widths in em for ASCII 0x20-0x7e\n"
        f"export const ADVANCES = {{\n{body}\n}} as const;\n"
    )
    print(f"{out} written")


if __name__ == "__main__":
    build(Path(sys.argv[1]), Path(sys.argv[2]))
    write_metrics(Path(sys.argv[2]), Path(__file__).resolve().parent.parent / "src" / "card" / "metrics.ts")
